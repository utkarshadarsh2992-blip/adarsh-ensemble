-- Recursive absolute-counter merge. Snapshots use stable identities for provider, slot, model, and day arrays.
create or replace function public.controller_merge_report_snapshot(p_old jsonb, p_new jsonb, p_path text default '')
returns jsonb language plpgsql immutable security definer
set search_path = pg_catalog, public, pg_temp
as $$
declare
  v_result jsonb;
  v_key text;
  v_new_value jsonb;
  v_new_item jsonb;
  v_old_item jsonb;
  v_merged jsonb;
  v_identity_field text;
  v_identity jsonb;
  v_index integer;
  v_field text;
begin
  if p_old is null then return p_new; end if;
  if jsonb_typeof(p_old) = 'object' and jsonb_typeof(p_new) = 'object' then
    v_result := p_old;
    for v_key, v_new_value in select key, value from jsonb_each(p_new) loop
      if p_old ? v_key then
        v_result := jsonb_set(v_result, array[v_key],
          public.controller_merge_report_snapshot(p_old -> v_key, v_new_value,
            case when p_path = '' then v_key else p_path || '.' || v_key end), true);
      else
        v_result := jsonb_set(v_result, array[v_key], v_new_value, true);
      end if;
    end loop;
    return v_result;
  elsif jsonb_typeof(p_old) = 'number' and jsonb_typeof(p_new) = 'number' then
    v_field := regexp_replace(p_path, '^.*[.]', '');
    if v_field in ('req','tok','answers','ok','shak','galat') or p_path like 'features.%' or p_path like 'days.by.%' then
      return to_jsonb(greatest((p_old #>> '{}')::numeric, (p_new #>> '{}')::numeric));
    end if;
    return p_new;
  elsif jsonb_typeof(p_old) = 'array' and jsonb_typeof(p_new) = 'array' then
    v_identity_field := case p_path
      when 'providers' then 'id'
      when 'providers.keys' then 'slot'
      when 'providers.keys.models' then 'model'
      when 'days' then 'day'
      else null end;
    if v_identity_field is null then return p_new; end if;
    v_result := p_old;
    for v_new_item in select value from jsonb_array_elements(p_new) loop
      v_identity := v_new_item -> v_identity_field;
      v_index := null;
      v_old_item := null;
      if v_identity is not null then
        select (ordinality - 1)::integer, value into v_index, v_old_item
        from jsonb_array_elements(p_old) with ordinality
        where value -> v_identity_field = v_identity
        limit 1;
      end if;
      if v_index is null then
        v_result := v_result || jsonb_build_array(v_new_item);
      else
        v_merged := public.controller_merge_report_snapshot(v_old_item, v_new_item, p_path);
        v_result := jsonb_set(v_result, array[v_index::text], v_merged, false);
      end if;
    end loop;
    return v_result;
  end if;
  return p_new;
end;
$$;

create or replace function public.controller_save_config(
  p_expected_revision bigint, p_config jsonb, p_actor_id uuid, p_reason text
) returns bigint language plpgsql security definer
set search_path = pg_catalog, public, pg_temp
as $$
declare v_current bigint; v_next bigint;
begin
  if p_expected_revision < 1 or jsonb_typeof(p_config) <> 'object' or p_reason is null or char_length(p_reason) > 300 then
    raise exception using errcode = '22023', message = 'invalid controller config';
  end if;
  perform pg_advisory_xact_lock(hashtext('adarsh-controller-config-v1'));
  select coalesce(max(revision), 0) into v_current from public.controller_config_revisions;
  if v_current <> p_expected_revision then raise exception using errcode = '40001', message = 'controller revision conflict'; end if;
  v_next := v_current + 1;
  insert into public.controller_config_revisions(revision, config, actor_id, reason)
    values(v_next, p_config, p_actor_id, p_reason);
  insert into public.controller_audit_log(event, revision, actor_id, reason)
    values('config_saved', v_next, p_actor_id, p_reason);
  return v_next;
end;
$$;

create or replace function public.controller_rollback_config(
  p_expected_revision bigint, p_target_revision bigint, p_actor_id uuid
) returns bigint language plpgsql security definer
set search_path = pg_catalog, public, pg_temp
as $$
declare v_current bigint; v_next bigint; v_config jsonb; v_reason text;
begin
  if p_expected_revision < 1 or p_target_revision < 1 then raise exception using errcode = '22023', message = 'invalid revision'; end if;
  perform pg_advisory_xact_lock(hashtext('adarsh-controller-config-v1'));
  select coalesce(max(revision), 0) into v_current from public.controller_config_revisions;
  if v_current <> p_expected_revision then raise exception using errcode = '40001', message = 'controller revision conflict'; end if;
  select config into v_config from public.controller_config_revisions where revision = p_target_revision;
  if v_config is null then raise exception using errcode = 'P0002', message = 'revision not found'; end if;
  v_next := v_current + 1;
  v_reason := 'Rollback to revision ' || p_target_revision::text;
  insert into public.controller_config_revisions(revision, config, actor_id, reason)
    values(v_next, v_config, p_actor_id, v_reason);
  insert into public.controller_audit_log(event, revision, actor_id, reason, metadata)
    values('config_rollback', v_next, p_actor_id, v_reason, jsonb_build_object('target_revision', p_target_revision));
  return v_next;
end;
$$;

create or replace function public.controller_create_pair_code(
  p_code_hash text, p_name text, p_expires_at timestamptz, p_actor_id uuid
) returns jsonb language plpgsql security definer
set search_path = pg_catalog, public, pg_temp
as $$
declare v_id uuid; v_expiry timestamptz;
begin
  if p_code_hash !~ '^[0-9a-f]{64}$' or p_name is null or char_length(p_name) not between 1 and 60
    or p_expires_at <= now() or p_expires_at > now() + interval '10 minutes' then
    raise exception using errcode = '22023', message = 'invalid pair code request';
  end if;
  insert into public.controller_pair_codes(code_hash, name, created_by, expires_at)
    values(p_code_hash, p_name, p_actor_id, p_expires_at) returning id, expires_at into v_id, v_expiry;
  insert into public.controller_audit_log(event, actor_id, reason, metadata)
    values('pair_code_created', p_actor_id, 'Pair code created', jsonb_build_object('name', p_name, 'expires_at', v_expiry));
  return jsonb_build_object('id', v_id, 'expires_at', v_expiry);
end;
$$;

create or replace function public.controller_consume_pair_code(
  p_code_hash text, p_device_token_hash text, p_device_name text
) returns jsonb language plpgsql security definer
set search_path = pg_catalog, public, pg_temp
as $$
declare v_code public.controller_pair_codes%rowtype; v_device uuid; v_revision bigint; v_config jsonb;
begin
  if p_code_hash !~ '^[0-9a-f]{64}$' or p_device_token_hash !~ '^[0-9a-f]{64}$'
    or p_device_name is null or char_length(p_device_name) not between 1 and 60 then
    raise exception using errcode = '28000', message = 'invalid pairing';
  end if;
  select * into v_code from public.controller_pair_codes
    where code_hash = p_code_hash and consumed_at is null and expires_at > now()
    for update;
  if not found then raise exception using errcode = '28000', message = 'invalid pairing'; end if;
  update public.controller_pair_codes set consumed_at = now() where id = v_code.id and consumed_at is null;
  if not found then raise exception using errcode = '28000', message = 'invalid pairing'; end if;
  select revision, config into v_revision, v_config from public.controller_config_revisions order by revision desc limit 1;
  if v_revision is null then raise exception using errcode = '55000', message = 'controller unavailable'; end if;
  insert into public.controller_devices(id, name, token_hash, config_revision, last_seen)
    values(gen_random_uuid(), p_device_name, p_device_token_hash, v_revision, now()) returning id into v_device;
  insert into public.controller_audit_log(event, device_id, reason, metadata)
    values('device_paired', v_device, 'Device paired', jsonb_build_object('pair_code_id', v_code.id));
  return jsonb_build_object('device_id', v_device, 'revision', v_revision, 'config', v_config);
end;
$$;

create or replace function public.controller_sync_device(
  p_device_id uuid, p_device_token_hash text, p_client_revision bigint, p_app_version text, p_reports jsonb
) returns jsonb language plpgsql security definer
set search_path = pg_catalog, public, pg_temp
as $$
declare v_device_id uuid; v_revision bigint; v_config jsonb; v_report jsonb; v_day date; v_now_utc date;
begin
  if p_device_token_hash !~ '^[0-9a-f]{64}$' or p_client_revision < 1
    or p_app_version is null or char_length(p_app_version) > 80
    or jsonb_typeof(p_reports) <> 'array' or jsonb_array_length(p_reports) > 14 then
    raise exception using errcode = '22023', message = 'invalid sync';
  end if;
  select id into v_device_id from public.controller_devices
    where id = p_device_id and token_hash = p_device_token_hash and revoked_at is null
    for update;
  if not found then raise exception using errcode = '28000', message = 'invalid device'; end if;
  v_now_utc := (now() at time zone 'UTC')::date;
  for v_report in select value from jsonb_array_elements(p_reports) loop
    begin v_day := (v_report ->> 'day_utc')::date;
    exception when others then raise exception using errcode = '22023', message = 'invalid report day'; end;
    if v_day < v_now_utc - 13 or v_day > v_now_utc or jsonb_typeof(v_report) <> 'object' then
      raise exception using errcode = '22023', message = 'invalid report day';
    end if;
    insert into public.controller_usage_snapshots(device_id, day_utc, report, updated_at)
      values(v_device_id, v_day, v_report, now())
    on conflict(device_id, day_utc) do update set
      report = public.controller_merge_report_snapshot(public.controller_usage_snapshots.report, excluded.report),
      updated_at = now();
  end loop;
  select revision, config into v_revision, v_config from public.controller_config_revisions order by revision desc limit 1;
  update public.controller_devices set app_version = p_app_version, last_seen = now(), config_revision = p_client_revision
    where id = v_device_id;
  return jsonb_build_object('revision', v_revision, 'config', v_config);
end;
$$;

create or replace function public.controller_revoke_device(p_device_id uuid, p_actor_id uuid)
returns boolean language plpgsql security definer
set search_path = pg_catalog, public, pg_temp
as $$
declare v_id uuid;
begin
  update public.controller_devices set revoked_at = now() where id = p_device_id and revoked_at is null returning id into v_id;
  if v_id is null then
    select id into v_id from public.controller_devices where id = p_device_id;
    if v_id is null then raise exception using errcode = 'P0002', message = 'device not found'; end if;
    return true;
  end if;
  insert into public.controller_audit_log(event, actor_id, device_id, reason)
    values('device_revoked', p_actor_id, v_id, 'Device revoked');
  return true;
end;
$$;

