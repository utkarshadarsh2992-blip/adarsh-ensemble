-- ADARSH Controller v1. Additive controller-only schema; News tables, functions, data,
-- cron jobs, and Vault secrets are intentionally untouched.

create table if not exists public.controller_admins (
  user_id uuid primary key references auth.users(id) on delete cascade,
  enabled boolean not null default true,
  created_at timestamptz not null default now()
);

create table if not exists public.controller_config_revisions (
  revision bigint primary key check (revision > 0),
  config jsonb not null check (jsonb_typeof(config) = 'object'),
  actor_id uuid references auth.users(id) on delete set null,
  reason text not null default '' check (char_length(reason) <= 300),
  created_at timestamptz not null default now()
);

create table if not exists public.controller_pair_codes (
  id uuid primary key default gen_random_uuid(),
  code_hash text not null unique check (code_hash ~ '^[0-9a-f]{64}$'),
  name text not null check (char_length(name) between 1 and 60),
  created_by uuid not null references auth.users(id) on delete restrict,
  created_at timestamptz not null default now(),
  expires_at timestamptz not null,
  consumed_at timestamptz,
  check (expires_at > created_at and expires_at <= created_at + interval '10 minutes')
);
create index if not exists controller_pair_codes_expiry_idx on public.controller_pair_codes (expires_at) where consumed_at is null;

create table if not exists public.controller_devices (
  id uuid primary key default gen_random_uuid(),
  name text not null check (char_length(name) between 1 and 60),
  token_hash text not null unique check (token_hash ~ '^[0-9a-f]{64}$'),
  app_version text not null default '' check (char_length(app_version) <= 80),
  last_seen timestamptz,
  config_revision bigint not null references public.controller_config_revisions(revision),
  revoked_at timestamptz,
  created_at timestamptz not null default now()
);
create index if not exists controller_devices_created_idx on public.controller_devices (created_at desc, id);

create table if not exists public.controller_usage_snapshots (
  device_id uuid not null references public.controller_devices(id) on delete cascade,
  day_utc date not null,
  report jsonb not null check (jsonb_typeof(report) = 'object' and octet_length(report::text) <= 262144),
  updated_at timestamptz not null default now(),
  primary key (device_id, day_utc)
);
create index if not exists controller_usage_day_idx on public.controller_usage_snapshots (day_utc desc, device_id);

create table if not exists public.controller_audit_log (
  id bigint generated by default as identity primary key,
  event text not null check (event in ('config_saved','config_rollback','pair_code_created','device_paired','device_revoked')),
  revision bigint references public.controller_config_revisions(revision),
  actor_id uuid references auth.users(id) on delete set null,
  device_id uuid,
  reason text not null default '' check (char_length(reason) <= 300),
  metadata jsonb not null default '{}'::jsonb check (jsonb_typeof(metadata) = 'object'),
  created_at timestamptz not null default now()
);
create index if not exists controller_audit_created_idx on public.controller_audit_log (created_at desc, id desc);

