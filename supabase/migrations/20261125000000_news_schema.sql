create or replace function public.claim_news_batch(p_limit integer default 30)
returns setof public.news_items
language plpgsql security definer set search_path = public
as $$
begin
  return query
  with picked as (
    select id from public.news_items
    where status = 'new'
    order by created_at asc
    for update skip locked
    limit greatest(1, least(coalesce(p_limit,30),30))
  )
  update public.news_items n set status='scoring'
  from picked where n.id=picked.id
  returning n.*;
end;
$$;

create or replace function public.bump_ai_usage(
  p_day date, p_provider text, p_model text, p_stage text,
  p_calls integer default 0, p_tokens_in integer default 0, p_tokens_out integer default 0
) returns public.ai_usage language sql security definer set search_path = public as $$
  insert into public.ai_usage(day,provider,model,stage,calls,tokens_in,tokens_out)
  values(p_day,p_provider,p_model,p_stage,p_calls,p_tokens_in,p_tokens_out)
  on conflict(day,provider,model,stage) do update set
    calls=public.ai_usage.calls+excluded.calls,
    tokens_in=public.ai_usage.tokens_in+excluded.tokens_in,
    tokens_out=public.ai_usage.tokens_out+excluded.tokens_out
  returning *;
$$;

create or replace function public.cleanup_news(p_keep_days integer default 30)
returns integer language plpgsql security definer set search_path = public as $$
declare removed integer;
begin
  delete from public.news_items where created_at < now() - make_interval(days => greatest(7,coalesce(p_keep_days,30)));
  get diagnostics removed = row_count;
  delete from public.seen_news where created_at < now() - interval '90 days';
  return removed;
end;
$$;

revoke all on function public.claim_news_batch(integer) from public, anon, authenticated;
revoke all on function public.bump_ai_usage(date,text,text,text,integer,integer,integer) from public, anon, authenticated;
revoke all on function public.cleanup_news(integer) from public, anon, authenticated;
grant execute on function public.claim_news_batch(integer) to service_role;
grant execute on function public.bump_ai_usage(date,text,text,text,integer,integer,integer) to service_role;
grant execute on function public.cleanup_news(integer) to service_role;
