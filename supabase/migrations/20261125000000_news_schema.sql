  kind text not null check (kind in ('company','topic','query')),
  region text not null check (region in ('IN','CN','US','RU','EU','WORLD')),
  tag_hint text check (tag_hint in ('AI','BIG-TECH','SPACE','ROBOTICS','PHYSICS','MATH','BIO-CHEM','ECON','WORLD','PAPER')),
  active boolean not null default true
);

create table if not exists public.user_devices (
  device_id text primary key,
  fcm_token text not null,
  platform text not null check (platform = 'android'),
  app_version text not null default '',
  updated_at timestamptz not null default now()
