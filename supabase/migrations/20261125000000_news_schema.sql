-- Change 1.5 news system. Run with the Supabase SQL editor as postgres/service owner.
-- No policies are intentional: only service_role inside Edge Functions can access these tables.

create extension if not exists pgcrypto;

create table if not exists public.feeds (
  id text primary key,
  url text not null unique,
  kind text not null check (kind in ('rss','atom','json','currents','newsdata','hf_papers')),
  grp text not null,
  region text not null check (region in ('IN','CN','US','RU','EU','WORLD')),
  tag_hint text check (tag_hint in ('AI','BIG-TECH','SPACE','ROBOTICS','PHYSICS','MATH','BIO-CHEM','ECON','WORLD','PAPER')),
  state_media boolean not null default false,
  every_min integer not null default 15 check (every_min between 5 and 1440),
  active boolean not null default true,
  last_fetch timestamptz,
  last_status integer,
  fail_count integer not null default 0,
  name text not null
);

create table if not exists public.seen_news (
  url_hash text primary key,
  created_at timestamptz not null default now()
);

create table if not exists public.news_items (
  id uuid primary key default gen_random_uuid(),
  title text not null,
  points text[] not null default '{}',
  tag text not null default 'WORLD' check (tag in ('AI','BIG-TECH','SPACE','ROBOTICS','PHYSICS','MATH','BIO-CHEM','ECON','WORLD','PAPER')),
  tags text[] not null default '{}',
  region text not null default 'WORLD' check (region in ('IN','CN','US','RU','EU','WORLD')),
  company text not null default '',
  activity text not null default 'other' check (activity in ('launch','model','datacentre','funding','acquisition','partnership','ipo','layoffs','policy','research','incident','other')),
  score integer check (score between 1 and 10),
  breaking boolean not null default false,
  verified text not null default 'none' check (verified in ('confirmed','partly','single','state-only','unconfirmed','none')),
  n_sources integer not null default 1,
  source text not null default '',
  url text not null,
  published_at timestamptz,
  created_at timestamptz not null default now(),
  read_at timestamptz,
  saved boolean not null default false,
  upvotes integer not null default 0,
  kind text not null default 'news' check (kind in ('news','paper')),
  status text not null default 'new' check (status in ('new','scoring','scored','skipped','dropped')),
  cluster_key text,
  title_norm text,
  feed_id text references public.feeds(id),
  raw_summary text not null default '',
  sources jsonb not null default '[]'::jsonb,
  why text not null default '',
  alerted_at timestamptz,
  state_media boolean not null default false,
  claim_tag text not null default '',
  scored_at timestamptz,
  tokens integer not null default 0
);

create unique index if not exists news_items_url_unique on public.news_items (url);
create index if not exists news_items_created_idx on public.news_items (created_at desc);
create index if not exists news_items_score_idx on public.news_items (score desc nulls last, created_at desc);
create index if not exists news_items_tag_idx on public.news_items (tag);
create index if not exists news_items_status_idx on public.news_items (status, created_at);
create index if not exists news_items_cluster_idx on public.news_items (cluster_key);
create index if not exists seen_news_created_idx on public.seen_news (created_at);

