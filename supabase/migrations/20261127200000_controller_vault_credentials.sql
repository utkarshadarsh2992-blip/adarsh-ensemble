-- Controller-managed credentials are encrypted by Supabase Vault. Public/app tables store only
-- Vault secret UUIDs and non-secret metadata; all functions are service_role-only.
create table if not exists public.controller_credential_slots (
  scope text not null check (scope in ('app','news','setup')),
  provider text not null,
  slot integer not null check (slot between 1 and 3),
  secret_id uuid not null,
  key_set boolean not null default false,
  account_id_set boolean not null default false,
  generation uuid not null default gen_random_uuid(),
  updated_at timestamptz not null default now(),
  primary key (scope, provider, slot),
  check (
    (scope = 'app' and ((provider in ('groq','openrouter','gemini','nvidia','cloudflare') and slot between 1 and 3) or (provider = 'tavily' and slot = 1))) or
    (scope = 'news' and provider in ('groq','tavily') and slot between 1 and 2) or
    (scope = 'setup' and provider in ('news','firebase') and slot = 1)
  ),
  check (scope = 'app' or account_id_set = false)
);

create table if not exists public.controller_credential_state (
  id smallint primary key check (id = 1),
  credential_revision bigint not null default 1 check (credential_revision > 0),
  reset_time text not null default '05:00' check (reset_time ~ '^(?:[01][0-9]|2[0-3]):[0-5][0-9]$'),
  timezone text not null default 'Asia/Kolkata' check (timezone = 'Asia/Kolkata'),
  device_settings jsonb not null default '{}'::jsonb check (jsonb_typeof(device_settings) = 'object'),
  updated_at timestamptz not null default now(),
  updated_by uuid references auth.users(id) on delete set null
);
insert into public.controller_credential_state(id) values (1) on conflict (id) do nothing;

create table if not exists public.controller_credential_events (
  id bigint generated by default as identity primary key,
  actor_id uuid references auth.users(id) on delete set null,
  event text not null check (event in ('set','delete','settings')),
  scope text,
  provider text,
  slot integer,
  generation uuid,
  created_at timestamptz not null default now()
);
create index if not exists controller_credential_events_created_idx on public.controller_credential_events(created_at desc, id desc);

alter table public.controller_credential_slots enable row level security;
alter table public.controller_credential_state enable row level security;
alter table public.controller_credential_events enable row level security;
revoke all on table public.controller_credential_slots, public.controller_credential_state, public.controller_credential_events from public, anon, authenticated, service_role;
revoke all on sequence public.controller_credential_events_id_seq from public, anon, authenticated, service_role;

create or replace function public.controller_credentials_state()
returns jsonb language plpgsql security definer
set search_path = pg_catalog, public, pg_temp
as $$
declare v_state public.controller_credential_state%rowtype; v_slots jsonb;
begin
  select * into v_state from public.controller_credential_state where id = 1;
  select coalesce(jsonb_agg(jsonb_build_object(
    'scope', scope, 'provider', provider, 'slot', slot, 'key_set', key_set,
    'account_id_set', account_id_set, 'generation', generation, 'updated_at', updated_at
  ) order by scope, provider, slot), '[]'::jsonb) into v_slots from public.controller_credential_slots;
  return jsonb_build_object(
    'ok', true,
    'revision', v_state.credential_revision,
    'slots', v_slots,
    'reset_time', v_state.reset_time,
    'timezone', v_state.timezone,
    'device_settings', v_state.device_settings,
    'setup_status', jsonb_build_object(
      'news', exists(select 1 from public.controller_credential_slots where scope='setup' and provider='news' and key_set),
      'firebase', exists(select 1 from public.controller_credential_slots where scope='setup' and provider='firebase' and key_set)
    )
  );
end;
$$;

create or replace function public.controller_credentials_write(
  p_scope text, p_provider text, p_slot integer, p_payload text,
  p_key_set boolean, p_account_id_set boolean, p_actor_id uuid
) returns jsonb language plpgsql security definer
set search_path = pg_catalog, public, vault, pg_temp
as $$
declare v_existing uuid; v_secret_id uuid; v_generation uuid := gen_random_uuid(); v_revision bigint; v_name text; v_payload jsonb;
begin
  if p_scope not in ('app','news','setup') or p_provider is null or p_slot not between 1 and 3
    or p_payload is null or char_length(p_payload) > 32768 or p_actor_id is null then
    raise exception using errcode='22023', message='invalid credential';
  end if;
  begin v_payload := p_payload::jsonb; exception when others then raise exception using errcode='22023', message='invalid credential'; end;
  if jsonb_typeof(v_payload) <> 'object' then raise exception using errcode='22023', message='invalid credential'; end if;
  if not (
    (p_scope='app' and ((p_provider in ('groq','openrouter','gemini','nvidia','cloudflare') and p_slot between 1 and 3) or (p_provider='tavily' and p_slot=1))) or
    (p_scope='news' and p_provider in ('groq','tavily') and p_slot between 1 and 2) or
    (p_scope='setup' and p_provider in ('news','firebase') and p_slot=1)
  ) then raise exception using errcode='22023', message='invalid credential'; end if;
  if p_scope <> 'app' and p_account_id_set then raise exception using errcode='22023', message='invalid credential'; end if;
  if p_key_set and not (v_payload ? 'key' or p_scope='setup') then raise exception using errcode='22023', message='invalid credential'; end if;

  perform 1 from public.controller_credential_state where id=1 for update;
  select secret_id into v_existing from public.controller_credential_slots
    where scope=p_scope and provider=p_provider and slot=p_slot for update;
  v_name := 'adarsh-controller-' || p_scope || '-' || p_provider || '-' || p_slot::text;
  if v_existing is null then
    v_secret_id := vault.create_secret(p_payload, v_name, 'ADARSH Controller managed credential', null::uuid);
  else
    v_secret_id := v_existing;
    perform vault.update_secret(v_secret_id, p_payload, v_name, 'ADARSH Controller managed credential', null::uuid);
  end if;
  insert into public.controller_credential_slots(scope,provider,slot,secret_id,key_set,account_id_set,generation,updated_at)
    values(p_scope,p_provider,p_slot,v_secret_id,p_key_set,p_account_id_set,v_generation,now())
  on conflict(scope,provider,slot) do update set secret_id=excluded.secret_id,key_set=excluded.key_set,
    account_id_set=excluded.account_id_set,generation=excluded.generation,updated_at=excluded.updated_at;
  update public.controller_credential_state set credential_revision=credential_revision+1,updated_at=now(),updated_by=p_actor_id where id=1
    returning credential_revision into v_revision;
  insert into public.controller_credential_events(actor_id,event,scope,provider,slot,generation)
    values(p_actor_id,'set',p_scope,p_provider,p_slot,v_generation);
  return jsonb_build_object('ok',true,'revision',v_revision,'generation',v_generation,'key_set',p_key_set,'account_id_set',p_account_id_set);
end;
$$;

create or replace function public.controller_credentials_delete(
  p_scope text, p_provider text, p_slot integer, p_actor_id uuid
) returns jsonb language plpgsql security definer
set search_path = pg_catalog, public, vault, pg_temp
as $$
declare v_secret_id uuid; v_generation uuid := gen_random_uuid(); v_revision bigint; v_name text;
begin
  if p_scope not in ('app','news','setup') or p_provider is null or p_slot not between 1 and 3 or p_actor_id is null then
    raise exception using errcode='22023', message='invalid credential'; end if;
  if not (
    (p_scope='app' and ((p_provider in ('groq','openrouter','gemini','nvidia','cloudflare') and p_slot between 1 and 3) or (p_provider='tavily' and p_slot=1))) or
    (p_scope='news' and p_provider in ('groq','tavily') and p_slot between 1 and 2) or
    (p_scope='setup' and p_provider in ('news','firebase') and p_slot=1)
  ) then raise exception using errcode='22023', message='invalid credential'; end if;
  perform 1 from public.controller_credential_state where id=1 for update;
  select secret_id into v_secret_id from public.controller_credential_slots where scope=p_scope and provider=p_provider and slot=p_slot for update;
  v_name := 'adarsh-controller-' || p_scope || '-' || p_provider || '-' || p_slot::text;
  if v_secret_id is null then v_secret_id := vault.create_secret('{}',v_name,'ADARSH Controller cleared credential',null::uuid);
  else perform vault.update_secret(v_secret_id,'{}',v_name,'ADARSH Controller cleared credential',null::uuid); end if;
  insert into public.controller_credential_slots(scope,provider,slot,secret_id,key_set,account_id_set,generation,updated_at)
    values(p_scope,p_provider,p_slot,v_secret_id,false,false,v_generation,now())
  on conflict(scope,provider,slot) do update set secret_id=excluded.secret_id,key_set=false,account_id_set=false,
    generation=excluded.generation,updated_at=excluded.updated_at;
  update public.controller_credential_state set credential_revision=credential_revision+1,updated_at=now(),updated_by=p_actor_id where id=1
    returning credential_revision into v_revision;
  insert into public.controller_credential_events(actor_id,event,scope,provider,slot,generation)
    values(p_actor_id,'delete',p_scope,p_provider,p_slot,v_generation);
  return jsonb_build_object('ok',true,'revision',v_revision,'generation',v_generation);
end;
$$;

create or replace function public.controller_credentials_settings_update(
  p_device_settings jsonb, p_reset_time text, p_actor_id uuid
) returns jsonb language plpgsql security definer
set search_path = pg_catalog, public, pg_temp
as $$
declare v_settings jsonb; v_time text; v_revision bigint;
begin
  if p_actor_id is null or (p_device_settings is not null and jsonb_typeof(p_device_settings)<>'object') then
    raise exception using errcode='22023', message='invalid settings'; end if;
  v_settings := coalesce(p_device_settings,'{}'::jsonb);
  if exists(select 1 from jsonb_object_keys(v_settings) k where k not in ('briefingOn','briefingTime','newsBriefing','briefingTelegram')) then
    raise exception using errcode='22023', message='invalid settings'; end if;
  if exists(select 1 from jsonb_each(v_settings) e where e.key in ('briefingOn','newsBriefing','briefingTelegram') and jsonb_typeof(e.value)<>'boolean') then
    raise exception using errcode='22023', message='invalid settings'; end if;
  if v_settings ? 'briefingTime' and (jsonb_typeof(v_settings->'briefingTime')<>'string' or (v_settings->>'briefingTime') !~ '^(?:[01][0-9]|2[0-3]):[0-5][0-9]$') then
    raise exception using errcode='22023', message='invalid settings'; end if;
  if p_reset_time is not null and p_reset_time !~ '^(?:[01][0-9]|2[0-3]):[0-5][0-9]$' then
    raise exception using errcode='22023', message='invalid reset time'; end if;
  update public.controller_credential_state set
    device_settings=device_settings || v_settings,
    reset_time=coalesce(p_reset_time,reset_time),
    credential_revision=credential_revision+1,updated_at=now(),updated_by=p_actor_id
    where id=1 returning credential_revision,reset_time into v_revision,v_time;
  insert into public.controller_credential_events(actor_id,event) values(p_actor_id,'settings');
  return jsonb_build_object('ok',true,'revision',v_revision,'reset_time',v_time,'timezone','Asia/Kolkata',
    'device_settings',(select device_settings from public.controller_credential_state where id=1));
end;
$$;

create or replace function public.controller_credentials_for_device(p_device_token_hash text)
returns jsonb language plpgsql security definer
set search_path = pg_catalog, public, vault, pg_temp
as $$
declare v_values jsonb := '{}'::jsonb; v_managed jsonb := '[]'::jsonb; v_setup jsonb := '{}'::jsonb; v_row record;
  v_payload jsonb; v_base text; v_suffix text; v_revision bigint; v_device_settings jsonb;
begin
  if p_device_token_hash !~ '^[0-9a-f]{64}$' or not exists(
    select 1 from public.controller_devices where token_hash=p_device_token_hash and revoked_at is null
  ) then raise exception using errcode='28000', message='invalid device'; end if;
  for v_row in select s.scope,s.provider,s.slot,s.secret_id,s.key_set,s.account_id_set,d.decrypted_secret
    from public.controller_credential_slots s left join vault.decrypted_secrets d on d.id=s.secret_id
    where s.scope in ('app','setup') order by s.scope,s.provider,s.slot loop
    if v_row.scope='setup' then
      if v_row.key_set and v_row.decrypted_secret is not null then
        v_setup := jsonb_set(v_setup,array[v_row.provider],v_row.decrypted_secret::jsonb,true);
      end if;
    else
      v_suffix := case when v_row.slot=1 then '' else '_'||v_row.slot::text end;
      v_base := case v_row.provider
        when 'groq' then 'GROQ_API_KEY' when 'openrouter' then 'OPENROUTER_API_KEY'
        when 'gemini' then 'GEMINI_API_KEY' when 'nvidia' then 'NVIDIA_API_KEY'
        when 'cloudflare' then 'CLOUDFLARE_API_TOKEN' when 'tavily' then 'TAVILY_API_KEY' else null end;
      if v_base is not null then
        v_managed := v_managed || jsonb_build_array(v_base||v_suffix);
        if v_row.key_set and v_row.decrypted_secret is not null then
          v_payload := v_row.decrypted_secret::jsonb;
          if jsonb_typeof(v_payload->'key')='string' and length(v_payload->>'key')>0 then
            v_values := jsonb_set(v_values,array[v_base||v_suffix],v_payload->'key',true);
          end if;
        end if;
        if v_row.provider='cloudflare' then
          v_managed := v_managed || jsonb_build_array('CLOUDFLARE_ACCOUNT_ID'||v_suffix);
          if v_row.account_id_set and v_row.decrypted_secret is not null then
            v_payload := coalesce(v_payload,v_row.decrypted_secret::jsonb);
            if jsonb_typeof(v_payload->'account_id')='string' and length(v_payload->>'account_id')>0 then
              v_values := jsonb_set(v_values,array['CLOUDFLARE_ACCOUNT_ID'||v_suffix],v_payload->'account_id',true);
            end if;
          end if;
        end if;
      end if;
    end if;
  end loop;
  select credential_revision,device_settings into v_revision,v_device_settings from public.controller_credential_state where id=1;
  return jsonb_build_object('credentials',jsonb_build_object('revision',v_revision,'values',v_values,'managed',v_managed),
    'device_settings',v_device_settings,'setup',v_setup);
end;
$$;

create or replace function public.controller_news_credentials(p_provider text)
returns jsonb language plpgsql security definer
set search_path = pg_catalog, public, vault, pg_temp
as $$
declare v_managed boolean; v_slots jsonb; v_reset text;
begin
  if p_provider not in ('groq','tavily') then raise exception using errcode='22023', message='invalid provider'; end if;
  select exists(select 1 from public.controller_credential_slots where scope='news' and provider=p_provider),
    (select reset_time from public.controller_credential_state where id=1)
    into v_managed,v_reset;
  select coalesce(jsonb_agg(jsonb_build_object('slot',s.slot,'key',d.decrypted_secret::jsonb->>'key','generation',s.generation)
      order by s.slot) filter (where s.key_set and d.decrypted_secret is not null and length(coalesce(d.decrypted_secret::jsonb->>'key',''))>0),'[]'::jsonb)
    into v_slots from public.controller_credential_slots s left join vault.decrypted_secrets d on d.id=s.secret_id
    where s.scope='news' and s.provider=p_provider;
  return jsonb_build_object('managed',v_managed,'slots',v_slots,'reset_time',v_reset,'timezone','Asia/Kolkata');
end;
$$;

