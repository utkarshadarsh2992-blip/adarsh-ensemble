"""NVIDIA media generation endpoints, isolated from the chat/model registry.

Generated bytes are stored app-privately and returned as an opaque media ID so
chat history never contains large base64 image/video payloads.
"""
from __future__ import annotations

import base64
import binascii
import json
import os
import re
import uuid
from pathlib import Path
from typing import Any

import httpx

FLUX_URL = "https://ai.api.nvidia.com/v1/genai/black-forest-labs/flux-3-image-klein"
COSMOS3_URL = "https://ai.api.nvidia.com/v1/cosmos/nvidia/cosmos3-nano"
# NVIDIA Build lists this NVCF function ID for cosmos3-nano. Its
# function-specific invocation host serves the Cosmos NIM generator route
# (`POST /v1/infer`). It is tried only when the public route above returns 404.
COSMOS3_FUNCTION_ID = "d09cd49d-d7f2-4361-928f-ea22af707249"
COSMOS3_FALLBACK_URL = f"https://{COSMOS3_FUNCTION_ID}.invocation.api.nvcf.nvidia.com/v1/infer"
COSMOS3_POLL_SECONDS = "300"
PROMPT_MAX = 2_000
VIDEO_FRAMES = {25, 49, 73, 121}
VIDEO_MAX_BYTES = 48 * 1024 * 1024
IMAGE_MAX_BYTES = 16 * 1024 * 1024
MAX_RESPONSE_BYTES = ((VIDEO_MAX_BYTES + 2) // 3) * 4 + 1024 * 1024
MAX_ERROR_BYTES = 64 * 1024
MEDIA_KEEP = 30
MEDIA_TOTAL_MAX_BYTES = 256 * 1024 * 1024
_ID = re.compile(r"^[0-9a-f]{32}$")


class MediaError(ValueError):
    """A short, user-safe media request error."""

    def __init__(self, message: str, status_code: int | None = None):
        super().__init__(message)
        self.status_code = status_code


def _root() -> Path:
    root = Path(os.environ.get("GENERATED_MEDIA_DIR", "/tmp/adarsh-generated-media"))
    root.mkdir(parents=True, exist_ok=True)
    return root


def _prompt(value: Any) -> str:
    if not isinstance(value, str):
        raise MediaError("Prompt required.")
    text = value.strip()
    if not text:
        raise MediaError("Prompt required.")
    if len(text) > PROMPT_MAX:
        raise MediaError(f"Prompt bahut lamba hai; {PROMPT_MAX} characters tak rakho.")
    return text


def _safe_provider_error(status_code: int, body: bytes | bytearray | None, api_key: str, truncated: bool = False) -> str:
    if truncated:
        return f"NVIDIA media request failed (HTTP {status_code}): error response exceeded the safe size limit"
    try:
        data = json.loads(body or b"")
        detail = data.get("detail") or data.get("error") or data.get("message") or data
        if isinstance(detail, (dict, list)):
            detail = str(detail)
        detail = str(detail)
    except Exception:
        detail = (body or b"").decode("utf-8", errors="replace")
    detail = detail.replace(api_key, "***").replace("\n", " ").strip()
    return f"NVIDIA media request failed (HTTP {status_code}): {detail[:260]}"


def _decode_payload(encoded: Any, kind: str) -> bytes:
    if not isinstance(encoded, str) or not encoded:
        raise MediaError("NVIDIA ne media output nahi diya. Prompt badal kar dobara try karo.")
    max_bytes = IMAGE_MAX_BYTES if kind == "image" else VIDEO_MAX_BYTES
    if len(encoded) > ((max_bytes + 2) // 3) * 4 + 8:
        raise MediaError("Generated file allowed size se badi hai; chhota video try karo.")
    try:
        raw = base64.b64decode(encoded, validate=True)
    except (ValueError, binascii.Error) as exc:
        raise MediaError("NVIDIA ka media response valid base64 nahi tha.") from exc
    if not raw or len(raw) > max_bytes:
        raise MediaError("Generated file allowed size se badi hai.")
    if kind == "image" and not raw.startswith(b"\xff\xd8\xff"):
        raise MediaError("NVIDIA image output JPEG nahi tha.")
    if kind == "video" and (len(raw) < 12 or raw[4:8] != b"ftyp"):
        raise MediaError("NVIDIA video output valid MP4 nahi tha.")
    return raw


def _save(kind: str, raw: bytes) -> str:
    ext = "jpg" if kind == "image" else "mp4"
    media_id = uuid.uuid4().hex
    root = _root()
    target = root / f"{media_id}.{ext}"
    partial = root / f".{media_id}.part"
    try:
        partial.write_bytes(raw)
        os.replace(partial, target)
    finally:
        try:
            partial.unlink(missing_ok=True)
        except OSError:
            pass
    _prune(root)
    return media_id


def _prune(root: Path) -> None:
    """Bound on-device artifact storage; newest generations are retained."""
    files = sorted(
        (p for p in root.iterdir() if p.is_file() and _ID.match(p.stem) and p.suffix in {".jpg", ".mp4"}),
        key=lambda p: p.stat().st_mtime_ns,
        reverse=True,
    )
    total = 0
    for index, path in enumerate(files):
        try:
            size = path.stat().st_size
            if index >= MEDIA_KEEP or total + size > MEDIA_TOTAL_MAX_BYTES:
                path.unlink(missing_ok=True)
            else:
                total += size
        except OSError:
            continue


async def _read_limited(response: httpx.Response, limit: int) -> tuple[bytearray | None, bool]:
    output = bytearray()
    async for chunk in response.aiter_bytes(chunk_size=64 * 1024):
        if len(output) + len(chunk) > limit:
            return None, True
        output.extend(chunk)
    return output, False


async def _post(url: str, body: dict, api_key: str, timeout: float, extra_headers: dict[str, str] | None = None) -> dict:
    limits = httpx.Limits(max_connections=2, max_keepalive_connections=0)
    headers = {
        "Authorization": f"Bearer {api_key}",
        "Accept": "application/json",
        "Content-Type": "application/json",
    }
    if extra_headers:
        headers.update(extra_headers)
    try:
        async with httpx.AsyncClient(
            timeout=httpx.Timeout(timeout, connect=20.0, write=45.0, pool=10.0),
            limits=limits,
            follow_redirects=False,
        ) as client:
            async with client.stream(
                "POST",
                url,
                headers=headers,
                json=body,
            ) as response:
                if response.status_code < 200 or response.status_code >= 300:
                    error_body, truncated = await _read_limited(response, MAX_ERROR_BYTES)
                    raise MediaError(
                        _safe_provider_error(response.status_code, error_body, api_key, truncated),
                        status_code=response.status_code,
                    )
                if response.status_code == 202:
                    raise MediaError(
                        "NVIDIA ne request queue kar di (HTTP 202), par video result abhi nahi aaya. Thodi der baad dobara try karo.",
                        status_code=202,
                    )
                content_length = response.headers.get("content-length")
                if content_length:
                    try:
                        if int(content_length) > MAX_RESPONSE_BYTES:
                            raise MediaError("NVIDIA response is larger than this device can safely process.")
                    except ValueError:
                        pass
                response_body, truncated = await _read_limited(response, MAX_RESPONSE_BYTES)
                if truncated:
                    raise MediaError("NVIDIA response is larger than this device can safely process.")
    except httpx.TimeoutException as exc:
        raise MediaError("NVIDIA request timeout ho gaya. Generate dobara manually try karo.") from exc
    except httpx.HTTPError as exc:
        raise MediaError(f"NVIDIA network request fail hua ({type(exc).__name__}).") from exc
    try:
        data = json.loads(response_body or b"")
    except (ValueError, UnicodeDecodeError) as exc:
        raise MediaError("NVIDIA se unreadable JSON response aaya.") from exc
    if not isinstance(data, dict):
        raise MediaError("NVIDIA response format samajh nahi aaya.")
    return data


async def generate(request: dict) -> dict:
    """Generate one FLUX image or one Cosmos3 text-to-video clip."""
    if not isinstance(request, dict):
        raise MediaError("Media request samajh nahi aaya.")
    kind = request.get("kind")
    if kind not in {"image", "video"}:
        raise MediaError("Image ya video generation select karo.")
    prompt = _prompt(request.get("prompt"))
    api_key = os.environ.get("NVIDIA_API_KEY", "").strip()
    if not api_key:
        raise MediaError("NVIDIA API key nahi mili. Settings > API keys mein NVIDIA key save karo.")

    if kind == "image":
        body = {
            "mode": "t2i",
            "prompt": prompt,
            "height": 1024,
            "width": 1024,
            "cfg_scale": 3.5,
            "steps": 35,
            "samples": 1,
        }
        data = await _post(FLUX_URL, body, api_key, timeout=240.0)
        artifacts = data.get("artifacts")
        encoded = artifacts[0].get("base64") if isinstance(artifacts, list) and artifacts and isinstance(artifacts[0], dict) else None
        raw = _decode_payload(encoded, "image")
        media_id = _save("image", raw)
        return {"type": "image", "mediaId": media_id, "mime": "image/jpeg", "prompt": prompt}

    frames = request.get("frames", 49)
    if isinstance(frames, bool) or not isinstance(frames, int) or frames not in VIDEO_FRAMES:
        raise MediaError("Video duration 1, 2, 3 ya 5 seconds mein choose karo.")
    body = {
        "model_mode": "text2video",
        "prompt": prompt,
        "resolution": "480_16_9",
        "num_frames": frames,
        "num_inference_steps": 35,
        "fps": 24,
        "seed": 0,
    }
    cosmos_headers = {"NVCF-POLL-SECONDS": COSMOS3_POLL_SECONDS}
    try:
        data = await _post(COSMOS3_URL, body, api_key, timeout=720.0, extra_headers=cosmos_headers)
    except MediaError as primary:
        if primary.status_code != 404:
            raise
        try:
            data = await _post(COSMOS3_FALLBACK_URL, body, api_key, timeout=720.0, extra_headers=cosmos_headers)
        except MediaError as backup:
            raise MediaError(
                f"Cosmos3 public route HTTP 404 tha; backup NVCF route: {backup}",
                status_code=backup.status_code,
            ) from backup
    raw = _decode_payload(data.get("b64_video"), "video")
    media_id = _save("video", raw)
    return {"type": "video", "mediaId": media_id, "mime": "video/mp4", "prompt": prompt, "frames": frames, "fps": 24}
