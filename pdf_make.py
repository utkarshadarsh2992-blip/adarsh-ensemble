"""Professional, structured PDF reports with no third-party dependency.

Chaquopy keeps the app small and predictable, so this writes PDF 1.4 by hand: base-14 fonts (Helvetica family and
Courier), a cover page, running header, wrapped paragraphs, headings, bullets, numbered lists, code blocks, a sources
section and "Page n of N" footers. Everything is WinAnsi text, which is what the reports contain (Hinglish or
English); characters outside WinAnsi are replaced instead of breaking the file.
"""
from __future__ import annotations

import datetime as _dt
import re

PAGE_W, PAGE_H = 595.0, 842.0          # A4 in points
MARGIN = 56.0
BODY = 10.5
LEAD = 15.0
TITLE = 22.0
H1 = 15.0
H2 = 12.0
SMALL = 8.5

_W = {" ": 0.28, ".": 0.28, ",": 0.28, ":": 0.28, ";": 0.28, "i": 0.24, "l": 0.24, "j": 0.28, "t": 0.30,
      "f": 0.30, "r": 0.35, "I": 0.28, "m": 0.86, "w": 0.74, "M": 0.86, "W": 0.94, "A": 0.66, "B": 0.66,
      "C": 0.72, "D": 0.72, "E": 0.66, "F": 0.61, "G": 0.78, "H": 0.72, "N": 0.72, "O": 0.78, "P": 0.66,
      "R": 0.72, "S": 0.66, "T": 0.61, "U": 0.72, "V": 0.61}


def _width(text: str, size: float) -> float:
    """Rough but consistent Helvetica advance width, good enough for clean wrapping."""
    total = 0.0
    for ch in text:
        if ch in _W:
            total += _W[ch]
        elif ch.isupper():
            total += 0.70
        elif ch.isdigit():
            total += 0.56
        elif ch in "()[]{}'\"|!":
            total += 0.33
        elif ch == "-":
            total += 0.33
        else:
            total += 0.52
    return total * size


def _esc(text: str) -> str:
    """WinAnsi-safe literal string for a PDF content stream."""
    out = []
    for ch in text:
        if ch in "()\\":
            out.append("\\" + ch)
        elif ch in "\n\r":
            out.append(" ")
        else:
            try:
                ch.encode("cp1252")      # bullets, dashes, quotes: all present in WinAnsi
                out.append(ch)
            except UnicodeEncodeError:
                out.append("?")          # Devanagari etc. is not in the base-14 fonts
    return "".join(out)


def _wrap(text: str, size: float, width: float) -> list[str]:
    words, lines, cur = text.split(), [], ""
    for w in words:
        trial = (cur + " " + w).strip()
        if _width(trial, size) <= width or not cur:
            cur = trial
        else:
            lines.append(cur)
            cur = w
    if cur:
        lines.append(cur)
    return lines or [""]


def _plain(text: str) -> str:
    """Strip the inline markdown the answers use, keep the words."""
    text = re.sub(r"\*\*(.+?)\*\*", r"\1", text or "")
    text = re.sub(r"(?<!\w)[*_](.+?)[*_](?!\w)", r"\1", text)
    text = re.sub(r"`([^`]+)`", r"\1", text)
    return text.replace("\t", "    ").strip()


class _Page:
    def __init__(self) -> None:
        self.ops: list[str] = []

    def text(self, x: float, y: float, size: float, font: str, s: str) -> None:
        self.ops.append(f"BT /{font} {size:.2f} Tf 1 0 0 1 {x:.2f} {y:.2f} Tm ({_esc(s)}) Tj ET")

    def rule(self, x1: float, y: float, x2: float, w: float = 0.6) -> None:
        self.ops.append(f"{w:.2f} w {x1:.2f} {y:.2f} m {x2:.2f} {y:.2f} l S")

    def box(self, x: float, y: float, w: float, h: float, grey: float = 0.95) -> None:
        self.ops.append(f"{grey:.2f} g {x:.2f} {y:.2f} {w:.2f} {h:.2f} re f 0 g")


def _cover(title: str, subtitle: str, meta: str) -> _Page:
    p = _Page()
    p.box(0, PAGE_H - 210, PAGE_W, 210, 0.94)
    p.text(MARGIN, PAGE_H - 96, 11, "F1", "ADARSH ENSEMBLE")
    p.rule(MARGIN, PAGE_H - 106, MARGIN + 120, 1.2)
    y = PAGE_H - 150
    for line in _wrap(title, TITLE, PAGE_W - 2 * MARGIN)[:3]:
        p.text(MARGIN, y, TITLE, "F1", line)
        y -= TITLE + 6
    if subtitle:
        for line in _wrap(subtitle, 11.5, PAGE_W - 2 * MARGIN)[:3]:
            p.text(MARGIN, y - 6, 11.5, "F3", line)
            y -= 16
    p.text(MARGIN, 120, 10, "F2", meta)
    p.rule(MARGIN, 104, PAGE_W - MARGIN, 0.6)
    p.text(MARGIN, 88, SMALL, "F2", "Generated by Adarsh Ensemble · personal research report")
    return p


def _render(markdown: str) -> list[_Page]:
    """Turn the report text into pages."""
    pages: list[_Page] = []
    p = _Page()
    pages.append(p)
    y = PAGE_H - MARGIN - 24
    width = PAGE_W - 2 * MARGIN
    in_code = False

    def new_page() -> None:
        nonlocal p, y
        p = _Page()
        pages.append(p)
        y = PAGE_H - MARGIN - 24

    def need(h: float) -> None:
        if y - h < MARGIN + 28:
            new_page()

    for raw in str(markdown or "").splitlines():
        line = raw.rstrip()
        if line.strip().startswith("```"):
            in_code = not in_code
            y -= 4
            continue
        if in_code:
            for seg in _wrap(_plain(line) or " ", 8.6, width - 16):
                need(12)
                p.box(MARGIN, y - 3.5, width, 12.6, 0.965)
                p.text(MARGIN + 7, y, 8.6, "F4", seg)
                y -= 12.4
            continue
        if not line.strip():
            y -= 6
            continue
        if line.startswith("# "):
            need(H1 + 16)
            y -= 6
            p.text(MARGIN, y, H1, "F1", _plain(line[2:])[:120])
            y -= 7
            p.rule(MARGIN, y, PAGE_W - MARGIN, 0.8)
            y -= H1
            continue
        if line.startswith("## "):
            need(H2 + 12)
            y -= 4
            p.text(MARGIN, y, H2, "F1", _plain(line[3:])[:140])
            y -= H2 + 4
            continue
        if line.startswith("### "):
            need(H2 + 8)
            p.text(MARGIN, y, BODY + 0.5, "F1", _plain(line[4:])[:160])
            y -= BODY + 7
            continue
        bullet = re.match(r"^\s*[-*\u2022]\s+(.*)$", line)
        num = re.match(r"^\s*(\d+)[.)]\s+(.*)$", line)
        if bullet or num:
            mark = "\u2022" if bullet else num.group(1) + "."
            body = bullet.group(1) if bullet else num.group(2)
            first = True
            for seg in _wrap(_plain(body), BODY, width - 22):
                need(LEAD)
                if first:
                    p.text(MARGIN + 2, y, BODY, "F2", mark)
                p.text(MARGIN + 20, y, BODY, "F2", seg)
                y -= LEAD
                first = False
            continue
        if re.match(r"^\s*[-—]{3,}\s*$", line):
            need(10)
            p.rule(MARGIN, y + 4, PAGE_W - MARGIN, 0.4)
            y -= 6
            continue
        for seg in _wrap(_plain(line), BODY, width):
            need(LEAD)
            p.text(MARGIN, y, BODY, "F2", seg)
            y -= LEAD
        y -= 2
    return pages


def build(title: str, body_markdown: str, *, subtitle: str = "", sources: list[dict] | None = None,
          author: str = "Adarsh Ensemble") -> bytes:
    """The whole document: cover, content, sources, footers."""
    today = _dt.date.today().strftime("%d %B %Y")
    pages: list[_Page] = [_cover(title or "Report", subtitle, f"{author} · {today}")]
    pages += _render(body_markdown)
    rows = [r for r in (sources or []) if isinstance(r, dict) and r.get("url")][:8]
    if rows:
        p = _Page()
        pages.append(p)
        y = PAGE_H - MARGIN - 24
        p.text(MARGIN, y, H1, "F1", "Sources")
        y -= 8
        p.rule(MARGIN, y, PAGE_W - MARGIN, 0.8)
        y -= H1
        for i, r in enumerate(rows, 1):
            label = str(r.get("label") or r.get("provider") or "")
            head = f"[S{i}] {label}: {_plain(str(r.get('title') or ''))}"[:150]
            for seg in _wrap(head, BODY, PAGE_W - 2 * MARGIN):
                p.text(MARGIN, y, BODY, "F2", seg)
                y -= LEAD
            for seg in _wrap(str(r.get("url") or ""), SMALL + 0.5, PAGE_W - 2 * MARGIN):
                p.text(MARGIN, y, SMALL + 0.5, "F3", seg)
                y -= 12
            y -= 6
    total = len(pages)
    for i, page in enumerate(pages, 1):
        if i == 1:
            continue
        page.text(MARGIN, PAGE_H - MARGIN + 6, SMALL, "F2", (title or "Report")[:80])
        page.rule(MARGIN, PAGE_H - MARGIN, PAGE_W - MARGIN, 0.4)
        foot = f"Page {i} of {total}"
        page.text(PAGE_W - MARGIN - _width(foot, SMALL), MARGIN - 14, SMALL, "F2", foot)
    return _assemble(pages, title, author)


def _assemble(pages: list[_Page], title: str, author: str) -> bytes:
    objs: list[bytes] = []

    def add(b: bytes) -> int:
        objs.append(b)
        return len(objs)          # 1-based object number

    font_ids = {}
    for name, base in (("F1", "Helvetica-Bold"), ("F2", "Helvetica"), ("F3", "Helvetica-Oblique"),
                       ("F4", "Courier")):
        font_ids[name] = add(f"<< /Type /Font /Subtype /Type1 /BaseFont /{base} /Encoding /WinAnsiEncoding >>".encode())
    pages_id = len(objs) + 1 + 2 * len(pages)     # reserved below
    kids, page_ids = [], []
    for page in pages:
        stream = "\n".join(page.ops).encode("cp1252", "replace")
        cid = add(b"<< /Length " + str(len(stream)).encode() + b" >>\nstream\n" + stream + b"\nendstream")
        resources = ("<< /Font << " + " ".join(f"/{k} {v} 0 R" for k, v in font_ids.items()) + " >> >>")
        pid = add(f"<< /Type /Page /Parent {pages_id} 0 R /MediaBox [0 0 {PAGE_W:.0f} {PAGE_H:.0f}] "
                  f"/Resources {resources} /Contents {cid} 0 R >>".encode())
        page_ids.append(pid)
        kids.append(f"{pid} 0 R")
    pages_obj = add(f"<< /Type /Pages /Kids [{' '.join(kids)}] /Count {len(pages)} >>".encode())
    assert pages_obj == pages_id, "page tree id must match the /Parent references"
    info = add(f"<< /Title ({_esc(title)[:120]}) /Author ({_esc(author)[:60]}) "
               f"/Producer (Adarsh Ensemble) /Creator (pdf_make) >>".encode())
    catalog = add(f"<< /Type /Catalog /Pages {pages_obj} 0 R >>".encode())

    out = bytearray(b"%PDF-1.4\n%\xe2\xe3\xcf\xd3\n")
    offsets = [0]
    for i, body in enumerate(objs, 1):
        offsets.append(len(out))
        out += f"{i} 0 obj\n".encode() + body + b"\nendobj\n"
    xref = len(out)
    out += f"xref\n0 {len(objs) + 1}\n".encode()
    out += b"0000000000 65535 f \n"
    for off in offsets[1:]:
        out += f"{off:010d} 00000 n \n".encode()
    out += (f"trailer\n<< /Size {len(objs) + 1} /Root {catalog} 0 R /Info {info} 0 R >>\n"
            f"startxref\n{xref}\n%%EOF\n").encode()
    return bytes(out)


def report(title: str, text: str, *, subtitle: str = "", sources: list[dict] | None = None) -> bytes:
    """Report from a finished answer: the answer becomes the body, its sources become the last page."""
    return build(title, text, subtitle=subtitle, sources=sources)
